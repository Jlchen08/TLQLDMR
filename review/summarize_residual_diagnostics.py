#!/usr/bin/env python3
"""Create descriptive residual diagnostics from locked Farm 6 point forecasts."""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / "review" / "selection_runs" / "selection_v1" / "within_site6"
OUT = ROOT / "review" / "residual_diagnostics.json"
TEX = ROOT / "TLQLDMR_R1" / "residual_diagnostics.tex"
CAPACITY_MW = 96.0
TAIL_FRACTION = 0.20
METHODS = ("Full", "NoVariance", "NoDiscrepancy", "WeightedSVQR", "TargetSVQR", "HistGBR")


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def read_residuals(path: Path) -> np.ndarray:
    residuals = []
    with path.open(newline="") as stream:
        for row in csv.DictReader(stream):
            residuals.append(float(row["y_true"]) - float(row["prediction"]))
    result = np.asarray(residuals, dtype=float)
    if len(result) != 2233 or not np.isfinite(result).all():
        raise ValueError(f"Unexpected prediction data in {path}")
    return result


def metrics(residual: np.ndarray) -> dict[str, float]:
    centered = residual - residual.mean()
    sd = np.sqrt(np.mean(centered ** 2))
    return {
        "mean_mw": float(residual.mean()),
        "sd_mw": float(sd),
        "skewness": float(np.mean(centered ** 3) / sd ** 3),
        "excess_kurtosis": float(np.mean(centered ** 4) / sd ** 4 - 3.0),
        "absolute_error_p95_mw": float(np.quantile(np.abs(residual), 0.95)),
        "tail_error_frequency": float(np.mean(np.abs(residual) > TAIL_FRACTION * CAPACITY_MW)),
    }


def main() -> None:
    records = []
    for method in METHODS:
        paths = sorted((RUN / method).glob("final_seed*/predictions.csv"))
        if method == "HistGBR" and len(paths) != 1:
            raise ValueError("HistGBR must have one deterministic prediction file")
        if method != "HistGBR" and len(paths) != 3:
            raise ValueError(f"{method} must have three landmark-seed prediction files")
        seed_metrics = [metrics(read_residuals(path)) for path in paths]
        summary = {key: float(np.mean([item[key] for item in seed_metrics])) for key in seed_metrics[0]}
        records.append({
            "method": method,
            "prediction_files": [{"path": str(path.relative_to(ROOT)), "sha256": digest(path)} for path in paths],
            "runs": len(paths),
            "per_run": seed_metrics,
            "mean_over_runs": summary,
        })
    payload = {
        "scope": "Farm 6 validation-selected point configurations; all 2,233 Q3-Q4 target test forecasts",
        "residual_definition": "observed power minus point forecast",
        "moment_definition": "empirical standardized central moments with population denominators; kurtosis is excess kurtosis",
        "tail_definition": f"absolute residual greater than {TAIL_FRACTION:.2f} of {CAPACITY_MW:.1f} MW nominal capacity",
        "aggregation": "compute each diagnostic within each landmark seed, then average diagnostics across seeds; HistGBR is deterministic",
        "records": records,
    }
    OUT.write_text(json.dumps(payload, indent=2, allow_nan=False) + "\n")

    labels = {
        "Full": "Full", "NoVariance": "No variance", "NoDiscrepancy": "No discrepancy",
        "WeightedSVQR": "Weighted SVQR", "TargetSVQR": "Target-only SVQR", "HistGBR": "HistGBR",
    }
    rows = []
    for record in records:
        x = record["mean_over_runs"]
        rows.append(
            f"{labels[record['method']]} & {record['runs']} & {x['mean_mw']:.3f} & {x['sd_mw']:.3f} & "
            f"{x['skewness']:.3f} & {x['excess_kurtosis']:.3f} & {x['absolute_error_p95_mw']:.3f} & "
            f"{100*x['tail_error_frequency']:.2f} \\\\"
        )
    TEX.write_text(r"""% Generated by review/summarize_residual_diagnostics.py; do not edit manually.
% BEGIN SELECTION BLOCK selection_residual_diagnostics
{\color{blue}Table~\ref{tab:selected_residual_diagnostics} replaces the earlier qualitative residual-density reading with numerical diagnostics on every one of the 2,233 Farm~6 test forecasts. Residual is observed minus predicted power. Skewness and excess kurtosis are empirical standardized central moments. Tail frequency uses the fixed descriptive threshold $|e|>0.20P_{\rm nominal}=19.2$\,MW, and $Q_{0.95}(|e|)$ reports tail magnitude without binning. Each statistic is computed within each landmark seed and then averaged; HistGBR is deterministic. The table is descriptive reused-test analysis and is not used for model selection or significance claims. Quantile reliability error is reported separately in Table~\ref{tab:probabilistic_scores}, because calibration is a property of the multi-quantile forecasts rather than of point residual density.}

\begin{table}[htbp]
\centering
\caption{\textcolor{blue}{Residual diagnostics for validation-selected Farm~6 point forecasts. Tail frequency is the percentage with absolute error above 19.2\,MW.}}
\label{tab:selected_residual_diagnostics}
{\color{blue}\small
\resizebox{\linewidth}{!}{%
\begin{tabular}{lrrrrrrr}
\toprule
Method & Runs & Mean (MW) & SD (MW) & Skew. & Excess kurt. & $Q_{0.95}(|e|)$ (MW) & Tail (\%) \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}}}
\end{table}
% END SELECTION BLOCK selection_residual_diagnostics
""")
    print(json.dumps({"json": str(OUT), "tex": str(TEX), "methods": len(records)}, indent=2))


if __name__ == "__main__":
    main()
